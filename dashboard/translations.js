// Apply translations dynamically to elements with data-i18n, data-i18n-placeholder attributes
function applyTranslations(lang) {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS['en'];
    
    // Set page title
    if (dict.pageTitle) {
        document.title = dict.pageTitle;
    }
    
    // Update elements with data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            // Preserve child tags/elements if it's formatted content, but for simple elements replace innerHTML
            if (el.children.length === 0 || key === 'sandboxIntro' || key === 'catalogSub') {
                el.innerHTML = dict[key];
            } else {
                // If it has children, we replace only the first child text node or do it custom
                let textNodeFound = false;
                for (let child of el.childNodes) {
                    if (child.nodeType === Node.TEXT_NODE && child.nodeValue.trim().length > 0) {
                        child.nodeValue = dict[key];
                        textNodeFound = true;
                        break;
                    }
                }
                if (!textNodeFound) {
                    el.innerHTML = dict[key]; // Fallback
                }
            }
        }
    });

    // Update inputs placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.setAttribute('placeholder', dict[key]);
        }
    });

    // Translate dynamic console placeholder if empty
    const consoleEl = document.getElementById("terminalConsole");
    if (consoleEl && consoleEl.innerHTML.includes("// Sandbox listo") || consoleEl.innerHTML.includes("// Sandbox ready") || consoleEl.innerHTML.includes("// Consola limpia") || consoleEl.innerHTML.includes("// Sandbox reiniciado")) {
        consoleEl.innerHTML = `<span class="text-gray-500">${dict.consolePlaceholder}</span><br>`;
    }
}

// Initial detection
function getActiveLanguage() {
    const urlParams = new URLSearchParams(window.location.search);
    const urlLang = urlParams.get('lang');
    if (urlLang && TRANSLATIONS[urlLang]) {
        localStorage.setItem('preferred_language', urlLang);
        return urlLang;
    }
    const localLang = localStorage.getItem('preferred_language');
    if (localLang && TRANSLATIONS[localLang]) {
        return localLang;
    }
    // Default is English as requested
    return 'en';
}

function changeLanguage(lang) {
    localStorage.setItem('preferred_language', lang);
    applyTranslations(lang);
    
    // Update active theme toggle buttons or links language
    const body = document.body;
    const btn = document.getElementById("themeToggleBtn");
    const dict = TRANSLATIONS[lang] || TRANSLATIONS['en'];
    if (btn) {
        if (body.classList.contains("light-mode")) {
            btn.innerHTML = `🌙 ${lang === 'es' ? 'Modo Oscuro' : 'Dark Mode'}`;
        } else {
            btn.innerHTML = `☀️ ${lang === 'es' ? 'Modo Claro' : 'Light Mode'}`;
        }
    }

    // Trigger alert or logs translation notification in the console
    const timestamp = new Date().toLocaleTimeString();
    const consoleEl = document.getElementById("terminalConsole");
    if (consoleEl) {
        consoleEl.innerHTML += `<span class="text-gray-500">[${timestamp}]</span> <span class="text-emerald-500 font-bold">[LANG] Language changed to: ${lang.toUpperCase()}</span><br>`;
    }
}

// Run on document load
document.addEventListener("DOMContentLoaded", () => {
    const activeLang = getActiveLanguage();
    
    // Set active select choice
    const select = document.getElementById("langSelect");
    if (select) {
        select.value = activeLang;
    }
    
    applyTranslations(activeLang);
});
